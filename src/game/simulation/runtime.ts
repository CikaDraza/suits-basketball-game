import { config, level, type Legend } from '../data/gameConfig';
import { createBallHandlingState } from './ballHandling';
import {
  INITIAL_MESSAGE,
  type BallFlight,
  type BallState,
  type Fighter,
  type InboundStage,
  type PhysicalInboundPass,
} from './types';

function createFighter(slot: number, legend: Legend): Fighter {
  return {
    x: level.spawns[slot].x,
    z: level.spawns[slot].z,
    energy: config.player.energyMax,
    mode: 'idle',
    angle: -Math.PI / 2,
    charge: 0,
    timer: 0,
    grace: 0,
    spin: 0,
    vx: 0,
    vz: 0,
    hand: 1,
    lastQ: -10,
    lastR: -10,
    taps: 0,
    prevQ: false,
    prevR: false,
    interceptUntil: -1,
    prevX: 0,
    aiClock: 0,
    rest: false,
    clumsy: 0,
    moving: 0,
    cooldown: 0,
    steal: 0,
    flopClock: 0,
    legend,
    handling: 'hold',
    dirHeld: 0,
    pendingMoveX: 0,
    pendingMoveZ: 0,
    inputResetVersion: 0,
    jab: 0,
    jabX: 0,
    jabZ: 0,
    jabCd: 0,
    bite: 0,
    biteX: 0,
    biteZ: 0,
    holdClock: 0,
    aiJab: false,
    grip: { x: 0, y: 0, z: 0, ok: false },
    gripOffset: { x: 0, y: 0, z: 0 },
    moveVX: 0,
    moveVZ: 0,
    passRequestAt: -Infinity,
  };
}

/** One source for initial state and resets, including transient flight and inbound state. */
export function createDuelState(
  legends: [Legend, Legend],
  seed = 42,
  revision = -1,
  start: 'inbound' | 'live' = 'inbound',
) {
  const spawn = level.spawns[level.initialOwner];
  return {
    time: 0,
    players: [createFighter(0, legends[0]), createFighter(1, legends[1])] as [Fighter, Fighter],
    owner: start === 'live' ? level.initialOwner : -1,
    lastTouch: level.initialOwner,
    ballState: (start === 'live' ? 'held' : 'inbound') as BallState,
    ballControl: createBallHandlingState(),
    ball:
      start === 'live'
        ? { x: spawn.x, y: config.ball.holdHeight, z: spawn.z }
        : { ...level.inbound },
    flight: {
      sx: 0,
      sy: 0,
      sz: 0,
      tx: 0,
      ty: 0,
      tz: 0,
      t: 0,
      duration: config.shots.flightDuration,
      arc: config.shots.arcHeight,
      made: false,
      points: config.score.inside,
      shooter: level.initialOwner,
      dunk: false,
    } as BallFlight,
    score: [0, 0] as [number, number],
    bumps: 0,
    shots: 0,
    dunks: 0,
    smashes: 0,
    flops: 0,
    fumbles: 0,
    interceptions: 0,
    pickups: 0,
    catches: 0,
    jabs: 0,
    bites: 0,
    dribbles: 0,
    violations: 0,
    shake: 0,
    rim: 0,
    event: { x: 0, z: 0, t: -10, color: '#f1a757' },
    message: INITIAL_MESSAGE,
    messageUntil: config.effects.textDuration,
    revision,
    resetTimer: 0,
    nextOwner: level.initialOwner,
    looseTimer: 0,
    inboundOwner: level.initialOwner,
    inboundStage: 'position' as InboundStage,
    inboundClock: start === 'live' ? 0 : config.inbound.positionTime,
    aiPassAt: 0,
    inboundPass: null as PhysicalInboundPass | null,
    lastInboundRequestId: 0,
    passes: 0,
    lobPasses: 0,
    chestPasses: 0,
    passDeflections: 0,
    hudTimer: 0,
    seed,
    p2Human: false,
    speaker: -1,
  };
}

export type DuelState = ReturnType<typeof createDuelState>;
